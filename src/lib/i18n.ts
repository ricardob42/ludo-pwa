const dicts: Record<Lang, Dict> = { es, en }

export type Vars = Record<string, string | number>
export type T = (key: Key, vars?: Vars) => string

export function translator(lang: Lang): T {
  const d = dicts[lang] ?? dicts[DEFAULT_LANG]
  return (key, vars) => d[key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars?.[k] ?? `{${k}}`))
}

export const colorName = (t: T, c: Seat['color']): string => t(`color_${c}` as Key)

/**
 * Seats created by the setup screen store language-neutral names ('#cpu', '#p1'...),
 * so switching language also switches CPU and default player names.
 */
export function seatName(seat: Seat, t: T): string {
  if (seat.name === '#cpu') return `${t('cpu')} ${colorName(t, seat.color)}`
  const m = /^#p(\d)$/.exec(seat.name)
  if (m) return `${t('player')} ${m[1]}`
  return seat.name
}
